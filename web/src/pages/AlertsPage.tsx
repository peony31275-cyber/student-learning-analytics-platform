import { keepPreviousData, useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { useState } from 'react';
import { Link, useSearchParams } from 'react-router';
import { RiskExplanation } from '../components/RiskFactors';
import {
  Card,
  EmptyState,
  FormError,
  PageHeader,
  Pagination,
  QueryState,
  RiskBadge,
  fmtDate,
} from '../components/ui';
import { api, qk } from '../services/api';
import type { AlertStatus, RiskAlert } from '../types/api';

export function AlertsPage() {
  const qc = useQueryClient();
  const [params, setParams] = useSearchParams();
  const [expanded, setExpanded] = useState<string | null>(null);
  const q = {
    page: Number(params.get('page') ?? 1),
    pageSize: 15,
    minLevel: params.get('minLevel') ?? 'MEDIUM',
    status: params.get('status') ?? 'OPEN',
    courseId: params.get('courseId') ?? undefined,
  };
  const update = (patch: Record<string, string>) => {
    const next = new URLSearchParams(params);
    for (const [k, v] of Object.entries(patch)) next.set(k, v);
    if (!('page' in patch)) next.delete('page');
    setParams(next, { replace: true });
  };

  const alerts = useQuery({
    queryKey: qk.alerts(q),
    queryFn: () => api.risk.list({ ...q, status: q.status === 'ALL' ? undefined : q.status }),
    placeholderData: keepPreviousData,
  });
  const courses = useQuery({
    queryKey: qk.courses({ pageSize: 100 }),
    queryFn: () => api.courses.list({ pageSize: 100 }),
  });

  const recalc = useMutation({
    mutationFn: () => api.risk.recalculate(q.courseId),
    onSuccess: () => {
      void qc.invalidateQueries({ queryKey: ['risk'] });
      void qc.invalidateQueries({ queryKey: ['analytics'] });
      void qc.invalidateQueries({ queryKey: ['students'] });
    },
  });

  return (
    <>
      <PageHeader
        title="Risk alerts"
        subtitle="Generated by the rule-based early-warning engine from grades, trends, attendance and completion"
        actions={
          <button className="btn" onClick={() => recalc.mutate()} disabled={recalc.isPending}>
            {recalc.isPending ? 'Recalculating…' : 'Recalculate now'}
          </button>
        }
      />
      <div className="stack">
        <FormError error={recalc.error} />
        {recalc.data && (
          <div className="alert-box success">
            Evaluated {recalc.data.evaluated} enrollments in {recalc.data.courses} course(s) in{' '}
            {recalc.data.durationMs} ms: {recalc.data.byLevel.HIGH} high,{' '}
            {recalc.data.byLevel.MEDIUM} medium, {recalc.data.byLevel.LOW} low.
          </div>
        )}
        <Card>
          <div className="filters">
            <select
              className="select"
              aria-label="Minimum level"
              value={q.minLevel}
              onChange={(e) => update({ minLevel: e.target.value })}
            >
              <option value="HIGH">High only</option>
              <option value="MEDIUM">Medium and high</option>
              <option value="LOW">All levels</option>
            </select>
            <select
              className="select"
              aria-label="Status"
              value={q.status}
              onChange={(e) => update({ status: e.target.value })}
            >
              <option value="OPEN">Open</option>
              <option value="ACKNOWLEDGED">Acknowledged</option>
              <option value="RESOLVED">Resolved</option>
              <option value="ALL">Any status</option>
            </select>
            <select
              className="select"
              aria-label="Course"
              value={q.courseId ?? ''}
              onChange={(e) => update({ courseId: e.target.value })}
            >
              <option value="">All courses</option>
              {courses.data?.data.map((c) => (
                <option key={c.id} value={c.id}>
                  {c.code}
                </option>
              ))}
            </select>
          </div>
          <QueryState
            query={alerts}
            isEmpty={(d) => d.data.length === 0}
            empty={<EmptyState title="No alerts match these filters" />}
          >
            {(d) => (
              <>
                <div
                  className="stack"
                  style={{ gap: 10, opacity: alerts.isPlaceholderData ? 0.6 : 1 }}
                >
                  {d.data.map((a) => (
                    <AlertRow
                      key={a.id}
                      alert={a}
                      open={expanded === a.id}
                      onToggle={() => setExpanded(expanded === a.id ? null : a.id)}
                    />
                  ))}
                </div>
                <Pagination meta={d.meta} onPage={(p) => update({ page: String(p) })} />
              </>
            )}
          </QueryState>
        </Card>
      </div>
    </>
  );
}

function AlertRow({
  alert,
  open,
  onToggle,
}: {
  alert: RiskAlert;
  open: boolean;
  onToggle: () => void;
}) {
  const qc = useQueryClient();
  const [note, setNote] = useState(alert.note ?? '');
  const update = useMutation({
    mutationFn: (status: AlertStatus) => api.risk.update(alert.id, { status, note: note || null }),
    onSuccess: () => {
      void qc.invalidateQueries({ queryKey: ['risk'] });
      void qc.invalidateQueries({ queryKey: ['analytics'] });
    },
  });
  return (
    <div className="card" style={{ padding: 14, boxShadow: 'none' }}>
      <div className="row">
        <RiskBadge level={alert.level} score={alert.score} />
        <Link to={`/students/${alert.student.id}`} style={{ fontWeight: 600 }}>
          {alert.student.firstName} {alert.student.lastName}
        </Link>
        <span className="subtle">
          {alert.course.code} · {alert.status.toLowerCase()} · {fmtDate(alert.computedAt)}
        </span>
        <span className="spacer" />
        <button className="btn btn-sm" onClick={onToggle} aria-expanded={open}>
          {open ? 'Hide details' : 'Why?'}
        </button>
      </div>
      {!open && alert.factors[0] && (
        <p className="muted" style={{ margin: '8px 0 0' }}>
          {alert.factors.map((f) => f.message).join(' · ')}
        </p>
      )}
      {open && (
        <div className="stack" style={{ marginTop: 12 }}>
          <RiskExplanation alert={alert} showHeader={false} />
          <FormError error={update.error} />
          <textarea
            className="input"
            rows={2}
            placeholder="Intervention notes (e.g. met with student, contacted family)…"
            aria-label="Notes"
            value={note}
            onChange={(e) => setNote(e.target.value)}
          />
          <div className="row">
            <button
              className="btn btn-sm btn-primary"
              disabled={update.isPending}
              onClick={() => update.mutate('ACKNOWLEDGED')}
            >
              Acknowledge
            </button>
            <button
              className="btn btn-sm"
              disabled={update.isPending}
              onClick={() => update.mutate('RESOLVED')}
            >
              Resolve
            </button>
            {alert.status !== 'OPEN' && (
              <button
                className="btn btn-sm"
                disabled={update.isPending}
                onClick={() => update.mutate('OPEN')}
              >
                Reopen
              </button>
            )}
          </div>
        </div>
      )}
    </div>
  );
}
